const { JSDOM } = require("jsdom"); const fs = require("fs"), path = require("path");
const SITE = process.argv[2], WEB = path.join(__dirname, "..", "web");
const idx = JSON.parse(fs.readFileSync(path.join(SITE, "index.json"), "utf8"));
const first = idx.matches[0], second = idx.matches[1];
const html = fs.readFileSync(path.join(WEB, "index.html"), "utf8").replace(/<script src="(config|app)\.js"><\/script>/g, "").replace(/<link[^>]+>/g, "");
const dom = new JSDOM(html, { url: "https://kwallo.pages.dev/", runScripts: "dangerously" }); const w = dom.window;
const opened = [];
w.fetch = async url => { url = String(url);
  if (url.endsWith("/api/live")) return { ok: true, json: async () => ({ [first.slug]: { state: "in", detail: "67'", hs: 1, as: 0 }, [second.slug]: { state: "post", detail: "FT", hs: 2, as: 2 } }) };
  const f = path.join(SITE, url.split("/api/site/")[1] || ""); return fs.existsSync(f) ? { ok: true, json: async () => JSON.parse(fs.readFileSync(f, "utf8")) } : { ok: false, status: 404 }; };
w.navigator.sendBeacon = () => true; w.scrollTo = () => {}; w.open = u => opened.push(u); if (!w.CSS) w.CSS = { escape: s => s };
w.eval(fs.readFileSync(path.join(WEB, "config.js"), "utf8")); w.eval(fs.readFileSync(path.join(WEB, "app.js"), "utf8"));
const sleep = ms => new Promise(r => setTimeout(r, ms)), $ = s => w.document.querySelector(s), $$ = s => [...w.document.querySelectorAll(s)];
const txt = el => el ? el.textContent.replace(/\s+/g, " ").trim() : null;
(async () => { await sleep(250);
  console.log("chips:", $$(".chip").map(txt).join(" | "));
  console.log("first card header:", txt($(".card-h")));
  console.log("live row:", txt($(".mrow.is-live")));
  console.log("finished row:", txt($$(".mrow")[1]));
  w.location.hash = "#/day/" + (first.kickoff ? new Date(first.kickoff).toISOString().slice(0, 10) : first.Date.slice(0, 10)) + "/live"; await sleep(250);
  console.log("Live filter shows:", $$("#app .mrow").length, "match(es):", $$("#app .mrow").map(r => txt(r.querySelector(".mteams"))).join(" / "));
  w.location.hash = "#/"; await sleep(250);
  $(".card-h").click(); await sleep(30);
  console.log("after folding the first card:", $(".card").classList.contains("folded"), "| remembered:", w.localStorage.getItem("kwallo:fold:" + $(".card").dataset.card));
  w.location.hash = "#/leagues"; await sleep(250);
  console.log("leagues cards folded at start:", $$(".card.folded").length, "of", $$(".card").length);
  const bl = $$(".card").find(c => c.dataset.card === "lg:bundesliga") || $$(".card")[0];
  bl.querySelector(".card-h").click(); await sleep(250);
  console.log("expanded", bl.dataset.card, "->", txt(bl.querySelector(".card-b")).slice(0, 160));
  w.location.hash = "#/match/" + first.slug; await sleep(300);
  console.log("match header:", txt($(".mhead")), "| stars:", $$(".mhead [data-fav]").map(s => s.dataset.fav).join(", "));
  $("[data-follow-match]").click(); await sleep(30);
  console.log("follow button now:", txt($("[data-follow-match]")), "| opened:", opened[0], "| favourite:", JSON.parse(w.localStorage.getItem("kwallo:fav")));
  process.exit(0);
})();
