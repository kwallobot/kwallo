const { JSDOM, VirtualConsole } = require("jsdom");
const fs = require("fs"), path = require("path");
const SITE = process.argv[2], WEB = path.join(__dirname, "..", "web");
const errors = [];
const vc = new VirtualConsole().on("jsdomError", e => errors.push(e.message));
const html = fs.readFileSync(path.join(WEB, "index.html"), "utf8").replace(/<script src="(config|app)\.js"><\/script>/g, "").replace(/<link[^>]+>/g, "");
const dom = new JSDOM(html, { url: "https://kwallo.pages.dev/", runScripts: "dangerously", virtualConsole: vc });
const w = dom.window;
w.fetch = async url => { const f = path.join(SITE, String(url).split("/api/site/")[1] || ""); return fs.existsSync(f) ? { ok: true, json: async () => JSON.parse(fs.readFileSync(f, "utf8")) } : { ok: false, status: 404 }; };
w.navigator.sendBeacon = () => true; w.scrollTo = () => {};
w.eval(fs.readFileSync(path.join(WEB, "config.js"), "utf8")); w.eval(fs.readFileSync(path.join(WEB, "app.js"), "utf8"));
const sleep = ms => new Promise(r => setTimeout(r, ms)), $ = s => w.document.querySelector(s), $$ = s => [...w.document.querySelectorAll(s)];
(async () => { await sleep(150);
  console.log("header:", $(".wordmark").textContent.replace(/\s+/g, " ").trim(), "| channel:", ($(".tg-channel") || {}).href, "| bot:", ($(".tg-bot") || {}).href);
  console.log("bottom bar:", $$(".bottom a").map(a => a.textContent.trim()).join(" · "));
  const lead = "egyptian-premier-league";
  w.location.hash = "#/comp/" + lead + "/leaders"; await sleep(150);
  const heads = () => $$("table.leaders thead th").map(t => t.textContent.trim().replace(/\s+/g, " ")).slice(0, 7).join(" | ");
  console.log("leaders headings:", heads() || ("EMPTY: " + $("#app").textContent.slice(0, 200)));
  const firstRows = () => $$("table.leaders tbody tr").slice(0, 3).map(r => [...r.children].slice(0, 5).map(td => td.textContent.trim()).join(" / "));
  console.log("top rows:", firstRows());
  const minTh = $('th[data-sort$="|minutes|total"]'); minTh.click(); await sleep(150);
  console.log("after tapping Minutes:", heads().split(" | ")[2], firstRows()[0]);
  $('th[data-sort$="|minutes|total"]').click(); await sleep(150);
  console.log("tap again (reversed):", heads().split(" | ")[2], firstRows()[0]);
  w.location.hash = "#/comp/bundesliga/table"; await sleep(150);
  console.log("competition title:", $("h1.title-row").textContent.replace(/\s+/g, " ").trim(), "| season line:", ($("#app p.muted") || {}).textContent);
  w.location.hash = "#/angles"; await sleep(150);
  const li = $("#app .angle");
  console.log("angle row right side:", li ? li.querySelector(".side").textContent.replace(/\s+/g, " ").trim() : "none");
  li.querySelector("[data-acca]").click(); await sleep(30);
  console.log("acca badge:", $$(".acca-count").map(b => b.hidden ? "hidden" : b.textContent).join(","));
  w.location.hash = "#/"; await sleep(150);
  console.log("times shown:", $$("#app .mrow .mtime").slice(0, 4).map(s => s.textContent).join(", "));
  console.log("errors:", errors.length ? errors : "none");
  process.exit(0);
})();
